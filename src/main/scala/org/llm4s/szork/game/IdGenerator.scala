package org.llm4s.szork.game

import java.util.UUID

/** Utility for generating prefixed, truncated IDs for better readability and distinguishability.
  *
  * Format: {prefix}-{8-char-uuid} Examples:
  *   - game-a3b2c1d4
  *   - sess-f5e6d7c8
  */
object IdGenerator {

  /** A new ID such as "game-a3b2c1d4": the prefix and eight hex digits. */
  private def generate(prefix: String): String = {
    val uuid = UUID.randomUUID().toString.replace("-", "").take(8).toLowerCase
    s"$prefix-$uuid"
  }

  /** Generate a game ID
    */
  def gameId(): String = generate("game")

  /** Generate a session ID
    */
  def sessionId(): String = generate("sess")

  /** Whether `id` is a game id as generated by [[gameId]] (e.g. "game-a3b2c1d4"). */
  def isValidGameId(id: String): Boolean = id != null && id.matches("game-[a-f0-9]{8}")
}
